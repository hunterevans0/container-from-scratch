//go:build linux

package runtime

import (
	"net"
	"strings"
	"testing"
)

// Tests for etc_linux.go: the /etc/hosts and /etc/resolv.conf a container
// gets. For how Go tests work, see "Tests" in doc.go.

// testResolvConf is a host's resolv.conf, with the kinds of servers a
// container mustn't get: a loopback one and an IPv6 one.
const testResolvConf = `# Generated by NetworkManager
nameserver 127.0.0.53
nameserver 192.168.1.1
nameserver fe80::1
search example.com lan
options edns0 trust-ad
`

// TestContainerResolvConf checks a container's resolv.conf, on the default
// network and on one with runt's DNS server.
func TestContainerResolvConf(t *testing.T) {
	host := parseResolvConf(testResolvConf)
	for _, test := range []struct {
		embeddedDNS bool
		want        string
	}{
		// Without the loopback server, which the container can't reach,
		// or the IPv6 one.
		{false, "nameserver 192.168.1.1\nsearch example.com lan\noptions edns0 trust-ad\n"},
		{true, "nameserver 127.0.0.11\nsearch example.com lan\noptions edns0 trust-ad ndots:0\n"},
	} {
		if got := containerResolvConf(host, test.embeddedDNS).String(); got != test.want {
			t.Errorf("containerResolvConf(embeddedDNS: %v):\n%s\nwant:\n%s", test.embeddedDNS, got, test.want)
		}
	}
	// The host's own setting wins.
	host = parseResolvConf("nameserver 10.0.0.1\noptions ndots:2\n")
	if got, want := containerResolvConf(host, true).String(), "nameserver 127.0.0.11\noptions ndots:2\n"; got != want {
		t.Errorf("with the host's ndots:\n%s\nwant:\n%s", got, want)
	}
	// With no server left, Docker's fallback.
	host = parseResolvConf("nameserver 127.0.0.1\n")
	if got, want := containerResolvConf(host, false).String(), "nameserver 8.8.8.8\nnameserver 8.8.4.4\n"; got != want {
		t.Errorf("with only a loopback server:\n%s\nwant:\n%s", got, want)
	}
}

// TestHostsFile checks a container's /etc/hosts, with an address and
// without one.
func TestHostsFile(t *testing.T) {
	hosts := hostsFile("web", net.IP{10, 88, 0, 2})
	for _, want := range []string{"127.0.0.1\tlocalhost\n", "::1\tlocalhost ip6-localhost ip6-loopback\n", "10.88.0.2\tweb\n"} {
		if !strings.Contains(hosts, want) {
			t.Errorf("hosts file is missing %q:\n%s", want, hosts)
		}
	}
	if hosts := hostsFile("web", nil); strings.Contains(hosts, "web") {
		t.Errorf("hosts file without an address names the host:\n%s", hosts)
	}
}
